#!/usr/bin/env python3
"""Generate Sym.java (SMuFL glyph table) from Leland metadata + SMuFL glyphnames.json.

Usage: python3 tools/gen_glyphs.py third_party/smufl app/src/main/java/io/github/vlesk/stave/engrave/Sym.java
"""
import json, sys, os

GLYPHS = """
noteheadDoubleWhole noteheadWhole noteheadHalf noteheadBlack noteheadXBlack
gClef fClef cClef gClef8vb gClef8va fClef8vb unpitchedPercussionClef1
restDoubleWhole restWhole restHalf restQuarter rest8th rest16th rest32nd rest64th
flag8thUp flag16thUp flag32ndUp flag64thUp flag8thDown flag16thDown flag32ndDown flag64thDown
accidentalDoubleFlat accidentalFlat accidentalNatural accidentalSharp accidentalDoubleSharp
timeSig0 timeSig1 timeSig2 timeSig3 timeSig4 timeSig5 timeSig6 timeSig7 timeSig8 timeSig9
timeSigCommon timeSigCutCommon
augmentationDot repeatDot
articAccentAbove articAccentBelow articStaccatoAbove articStaccatoBelow articTenutoAbove articTenutoBelow
articMarcatoAbove articMarcatoBelow articStaccatissimoAbove articStaccatissimoBelow
fermataAbove fermataBelow ornamentTrill ornamentMordent ornamentTurn breathMarkComma caesura
dynamicPPP dynamicPP dynamicPiano dynamicMP dynamicMF dynamicForte dynamicFF dynamicFFF
dynamicFortePiano dynamicSforzato dynamicSforzando1 dynamicRinforzando2
brace bracketTop bracketBottom segno coda
metNoteDoubleWhole metNoteWhole metNoteHalfUp metNoteQuarterUp metNote8thUp metNote16thUp metNote32ndUp
metAugmentationDot
tuplet0 tuplet1 tuplet2 tuplet3 tuplet4 tuplet5 tuplet6 tuplet7 tuplet8 tuplet9
keyboardPedalPed keyboardPedalUp
""".split()

def main(src, out):
    meta = json.load(open(os.path.join(src, 'leland_metadata.json')))
    names = json.load(open(os.path.join(src, 'glyphnames.json')))
    bb = meta['glyphBBoxes']; anc = meta.get('glyphsWithAnchors', {})
    eng = meta['engravingDefaults']
    L = []
    w = L.append
    w('// GENERATED by tools/gen_glyphs.py from the Leland font metadata (SIL OFL 1.1) - do not edit.')
    w('package io.github.vlesk.stave.engrave;\n')
    w('/** SMuFL glyph table for the Leland music font. All metrics are in staff spaces, y up (SMuFL convention). */')
    w('public final class Sym {')
    w('    private Sym() {}')
    for i, g in enumerate(GLYPHS):
        w('    public static final int %s = %d;' % (g, i))
    w('    public static final int COUNT = %d;' % len(GLYPHS))
    w('    public static final String[] NAMES = {%s};' % ', '.join('"%s"' % g for g in GLYPHS))
    w('    public static final char[] CODE = {%s};' % ', '.join("(char) 0x" + names[g]['codepoint'][2:] for g in GLYPHS))
    def f(v): return ('%.3ff' % v)
    rows = []
    for g in GLYPHS:
        b = bb[g]
        rows.append('{%s, %s, %s, %s}' % (f(b['bBoxSW'][0]), f(b['bBoxSW'][1]), f(b['bBoxNE'][0]), f(b['bBoxNE'][1])))
    w('    /** {swX, swY, neX, neY} */')
    w('    public static final float[][] BBOX = {%s};' % ',\n        '.join(rows))
    def anch(key):
        rows = []
        for g in GLYPHS:
            a = anc.get(g, {}).get(key)
            rows.append('null' if a is None else '{%s, %s}' % (f(a[0]), f(a[1])))
        return rows
    w('    public static final float[][] STEM_UP_SE = {%s};' % ', '.join(anch('stemUpSE')))
    w('    public static final float[][] STEM_DOWN_NW = {%s};' % ', '.join(anch('stemDownNW')))
    for k in ['staffLineThickness','stemThickness','beamThickness','beamSpacing','legerLineThickness','legerLineExtension',
              'thinBarlineThickness','thickBarlineThickness','barlineSeparation','thinThickBarlineSeparation','repeatBarlineDotSeparation',
              'tieMidpointThickness','tieEndpointThickness','bracketThickness','tupletBracketThickness','hairpinThickness']:
        w('    public static final float %s = %s;' % (k.upper() if False else k, f(eng[k])))
    w('    public static int byName(String n) { for (int i = 0; i < COUNT; i++) if (NAMES[i].equals(n)) return i; return -1; }')
    w('    public static float width(int g) { return BBOX[g][2] - BBOX[g][0]; }')
    w('    public static String str(int g) { return String.valueOf(CODE[g]); }')
    w('}')
    open(out, 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
